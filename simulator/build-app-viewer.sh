#!/usr/bin/env bash
# Package the simulator page for the app's in-browser 3D viewer.
#
#   simulator/build-app-viewer.sh           # writes the generated module
#   simulator/build-app-viewer.sh --check   # fails if it is out of date
#
# The app serves the same page build.sh writes, with the project's own scene in
# place of a file. Its parts (head, body, sim/*.js) and the rules they apply are
# copied into src/modules/model/viewer-assets.generated.ts, so a deployed app
# needs neither Python nor the simulator folder at runtime. Re-run after any
# change under simulator/ or to migration 0017; --check is what CI runs.
set -euo pipefail
cd "$(dirname "$0")/.."
PY=engines/.venv/bin/python
TARGET=src/modules/model/viewer-assets.generated.ts
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

"$PY" simulator/rules.py > "$TMP/rules.json"
"$PY" simulator/rules.py --device-rules > "$TMP/device-rules.json"
cat simulator/head.html simulator/body.html > "$TMP/page.html"
cat simulator/sim/*.js > "$TMP/sim.js"

node -e '
const fs = require("fs");
const [dir, out] = process.argv.slice(1);
const read = (f) => fs.readFileSync(dir + "/" + f, "utf8");
const s = JSON.stringify;
fs.writeFileSync(out, [
  "// GENERATED by simulator/build-app-viewer.sh from simulator/ and migration 0017.",
  "// Do not edit. Re-run the script after changing either.",
  "",
  "export const VIEWER_PAGE = " + s(read("page.html")) + ";",
  "export const VIEWER_JS = " + s(read("sim.js")) + ";",
  "export const VIEWER_RULES: unknown = " + read("rules.json").trim() + ";",
  "export const DEVICE_RULES: Record<string, unknown> = " + read("device-rules.json").trim() + ";",
  "",
].join("\n"));
' "$TMP" "$TMP/out.ts"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$TMP/out.ts" "$TARGET"; then
    echo "  FAIL  $TARGET is out of date: run simulator/build-app-viewer.sh" >&2
    exit 1
  fi
  echo "  ok    $TARGET matches simulator/ and the rules library"
else
  mkdir -p "$(dirname "$TARGET")"
  cp "$TMP/out.ts" "$TARGET"
  echo "  wrote $TARGET ($(wc -c < "$TARGET" | tr -d " ") bytes)"
fi
