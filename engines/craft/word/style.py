"""One shared look for every Word document the engines produce.

Plain and consistent on purpose: A4, one typeface, a title, a two-column
metadata block, then content. No logo and no letterhead, because those are
SmartPage's and are not mine to invent. Dropping a real template into
storage and pointing `word.fill_template` at it overrides all of this.
"""
from __future__ import annotations

import docx
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

BODY_FONT = "Calibri"          # substituted automatically where absent
BODY_SIZE = Pt(10.5)
TITLE_SIZE = Pt(18)
LABEL_GREY = RGBColor(0x59, 0x59, 0x59)

# Documents that state a conclusion carry this. It is not branding: it is the
# difference between a generated proposal and a signed submittal.
PROPOSAL_NOTE = ("Generated by SmartPage Intelligence from captured project and "
                 "specification data. A proposal for engineering review; not a "
                 "submittal until signed.")


def new_document() -> docx.document.Document:
    """A4, 2 cm margins, one typeface."""
    doc = docx.Document()
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    for attr in ("top_margin", "bottom_margin", "left_margin", "right_margin"):
        setattr(section, attr, Cm(2.0))

    normal = doc.styles["Normal"]
    normal.font.name = BODY_FONT
    normal.font.size = BODY_SIZE
    # python-docx sets the Latin font only; east-asian must be set in the XML or
    # Word falls back to its own default for anything non-ASCII.
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), BODY_FONT)
    normal.paragraph_format.space_after = Pt(6)
    return doc


def add_title(doc, text: str) -> None:
    par = doc.add_paragraph()
    par.paragraph_format.space_after = Pt(14)
    run = par.add_run(text)
    run.bold = True
    run.font.size = TITLE_SIZE
    run.font.name = BODY_FONT


def add_meta(doc, pairs: list[tuple[str, str]]) -> None:
    """The label/value block under the title. Borderless, so it reads as text."""
    table = doc.add_table(rows=0, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    for label, value in pairs:
        cells = table.add_row().cells
        cells[0].width = Cm(4.5)
        cells[1].width = Cm(12.5)
        lp = cells[0].paragraphs[0]
        lp.paragraph_format.space_after = Pt(2)
        lr = lp.add_run(label)
        lr.font.color.rgb = LABEL_GREY
        lr.font.size = Pt(9)
        vp = cells[1].paragraphs[0]
        vp.paragraph_format.space_after = Pt(2)
        vp.add_run(value).bold = True
    doc.add_paragraph()


def add_heading(doc, text: str) -> None:
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(10)
    par.paragraph_format.space_after = Pt(4)
    run = par.add_run(text)
    run.bold = True
    run.font.size = Pt(11)


def add_footer(doc, text: str) -> None:
    par = doc.sections[0].footer.paragraphs[0]
    par.text = text
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in par.runs:
        run.font.size = Pt(8)
        run.font.color.rgb = LABEL_GREY


def add_note(doc, text: str = PROPOSAL_NOTE) -> None:
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(16)
    run = par.add_run(text)
    run.italic = True
    run.font.size = Pt(8)
    run.font.color.rgb = LABEL_GREY


def style_table(table) -> None:
    """Grid lines, bold header row, 9 pt."""
    table.style = "Table Grid"
    for i, row in enumerate(table.rows):
        for cell in row.cells:
            for par in cell.paragraphs:
                par.paragraph_format.space_after = Pt(2)
                for run in par.runs:
                    run.font.size = Pt(9)
                    if i == 0:
                        run.bold = True
